"""
Updates ts_pin.json to the newest Tax-Simulator commit.

USAGE: python update_ts_pin.py [--write] [--sha SHA]

Without --write, this script only reports which ts_pin.json entries
would change and which of the Tax-Simulator files used by run_ts.R
changed between the pinned and the new commit.  The new commit is
checked to contain the files run_ts.R sources before anything is
written, so ts_pin.json is never changed to an unusable pin.

The R package versions in ts_pin.json are not changed by this script;
edit them by hand if the new Tax-Simulator commit needs newer packages.

After writing a new pin, all the TS outputs must be regenerated with
run_ts.py --all --force and every difference must be re-examined.
"""

import argparse
import datetime
import json
import sys
import urllib.error
import urllib.request
import run_ts  # pylint: disable=import-error


GITHUB_API = "https://api.github.com/repos"
URL_TIMEOUT = 30  # seconds

# Tax-Simulator files that run_ts.R needs (see ts_source_files in
# ts_pin.json); a new commit must contain all of them
REQUIRED_FILES = [
    "src/calc/do_taxes.R",
    "src/calc/utils.R",
    "src/data/tax_law.R",
    "src/misc/utils.R",
    "config/scenarios/tax_law/baseline",
]

# prefixes of the Tax-Simulator paths whose changes can affect the
# TS outputs generated by run_ts.R
RELEVANT_PREFIXES = (
    "src/calc/",
    "src/data/tax_law.R",
    "src/misc/utils.R",
    "config/scenarios/tax_law/baseline/",
)


def get_json(url):
    """
    Return the decoded JSON response to an HTTP GET request for URL.
    """
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": "Tax-Calculator update_ts_pin.py",
            "Accept": "application/vnd.github+json",
        },
    )
    with urllib.request.urlopen(req, timeout=URL_TIMEOUT) as resp:
        return json.load(resp)


def repo_api(pin):
    """
    Return the GitHub API URL of the Tax-Simulator repository in PIN.
    """
    repo_url = pin["tax_simulator_repo"]
    owner_repo = repo_url.removeprefix("https://github.com/").rstrip("/")
    return f"{GITHUB_API}/{owner_repo}"


def newest_commit(api, sha=None):
    """
    Return (sha, date) tuple for the specified SHA (or for the newest
    commit on the default branch if SHA is None) in the GitHub API repo.
    """
    if sha is None:
        sha = get_json(api)["default_branch"]
    commit = get_json(f"{api}/commits/{sha}")
    date = commit["commit"]["committer"]["date"][:10]
    return commit["sha"], date


def check_required_files(api, sha):
    """
    Raise RuntimeError if commit SHA lacks any of the REQUIRED_FILES.
    """
    missing = []
    for path in REQUIRED_FILES:
        try:
            get_json(f"{api}/contents/{path}?ref={sha}")
        except urllib.error.HTTPError as err:
            if err.code != 404:
                raise
            missing.append(path)
    if missing:
        raise RuntimeError(
            f"Tax-Simulator commit {sha[:12]} lacks files needed by "
            "run_ts.R: " + ", ".join(missing)
        )


def relevant_changes(api, old_sha, new_sha):
    """
    Return (ahead_by, behind_by, files, truncated) tuple describing
    the changes from OLD_SHA to NEW_SHA, where files is a list of
    (status, path) tuples for the changed files that can affect the
    TS outputs, and truncated is True if GitHub did not list every
    changed file.
    """
    comp = get_json(f"{api}/compare/{old_sha}...{new_sha}")
    files = [
        (fil["status"], fil["filename"])
        for fil in comp.get("files", [])
        if fil["filename"].startswith(RELEVANT_PREFIXES)
    ]
    truncated = len(comp.get("files", [])) >= 300
    return comp["ahead_by"], comp["behind_by"], files, truncated


def changes(old, new):
    """
    Return list of (key, old_value, new_value) tuples for the version
    entries that differ between the OLD and NEW pins.
    """
    return [
        (key, old.get(key), val)
        for key, val in new.items()
        if key != "pinned_on" and val != old.get(key)
    ]


def write_pin(old, new):
    """
    Write NEW pin to ts_pin.json by replacing, in the text of the OLD
    pin file, each string value that differs between OLD and NEW, so
    the file's layout is preserved.
    """
    text = run_ts.PIN_FILE.read_text(encoding="utf-8")
    for key, oldval, newval in changes(old, new) + [
        ("pinned_on", old["pinned_on"], new["pinned_on"])
    ]:
        old_item = f"{json.dumps(key)}: {json.dumps(oldval)}"
        if text.count(old_item) != 1:
            raise RuntimeError(f"cannot find {old_item} in ts_pin.json")
        text = text.replace(
            old_item, f"{json.dumps(key)}: {json.dumps(newval)}"
        )
    if json.loads(text) != new:
        raise RuntimeError("ts_pin.json update failed")
    run_ts.PIN_FILE.write_text(text, encoding="utf-8")


def report_changes(ahead, behind, files, truncated):
    """
    Write to stdout the commit counts and the changed files returned
    by relevant_changes.
    """
    sys.stdout.write(
        f"new commit is {ahead} commits ahead of and {behind} commits "
        f"behind the pinned commit;\n{len(files)} files used by "
        "run_ts.R were changed by the commits ahead:\n"
    )
    for status, path in files:
        sys.stdout.write(f"  {status:9s} {path}\n")
    if truncated:
        sys.stdout.write(
            "  (GitHub lists at most 300 changed files, so this list "
            "may be incomplete)\n"
        )


def main():
    """
    Report (and with --write save) the newest ts_pin.json information.
    """
    parser = argparse.ArgumentParser(
        prog="python update_ts_pin.py",
        description=(
            "Updates ts_pin.json to the newest Tax-Simulator commit "
            "(a dry run unless --write)."
        ),
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="write the new pin to ts_pin.json",
    )
    parser.add_argument(
        "--sha",
        default=None,
        help="pin this Tax-Simulator commit instead of the newest",
    )
    args = parser.parse_args()
    pin = run_ts.read_pin()
    api = repo_api(pin)
    try:
        sha, date = newest_commit(api, args.sha)
        if sha == pin["tax_simulator_sha"]:
            sys.stdout.write("ts_pin.json is already up to date\n")
            return 0
        check_required_files(api, sha)
        comparison = relevant_changes(
            api, pin["tax_simulator_sha"], sha
        )
    except (RuntimeError, OSError) as err:
        sys.stderr.write(f"ERROR: {err}\n")
        return 1
    new = dict(pin)
    new["tax_simulator_sha"] = sha
    new["tax_simulator_sha_date"] = date
    for key, oldval, newval in changes(pin, new):
        sys.stdout.write(f"{key}: {oldval} --> {newval}\n")
    report_changes(*comparison)
    if not args.write:
        sys.stdout.write("dry run: use --write to update ts_pin.json\n")
        return 0
    new["pinned_on"] = datetime.date.today().isoformat()
    try:
        write_pin(pin, new)
    except RuntimeError as err:
        sys.stderr.write(f"ERROR: {err}\n")
        return 1
    sys.stdout.write(
        f"wrote {run_ts.PIN_FILE.name}; next steps:\n"
        "  1. update the R package versions in ts_pin.json if needed\n"
        "  2. regenerate all TS outputs with run_ts.py --all --force\n"
        "     (and update ts_law_overrides.csv if run_ts.R says so)\n"
        "  3. run validate.py and re-examine every difference\n"
        "  4. update test_results.expect, VARIABLES.md, and SUMMARY.md\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
